def generate_augmented_dataset() -> List[Dict]:
    templates = get_24_sign_templates()
    samples = []
    np.random.seed(42)

    for label, pts in templates.items():
        pts_arr = np.array(pts, dtype=np.float32)

        # 5 rotation variations: -20, -10, 0, 10, 20 degrees
        for angle_deg in [-20, -10, 0, 10, 20]:
            angle_rad = math.radians(angle_deg)
            cos_a = math.cos(angle_rad)
            sin_a = math.sin(angle_rad)

            origin = pts_arr[0]
            rotated = pts_arr.copy()
            dx = pts_arr[:, 0] - origin[0]
            dy = pts_arr[:, 1] - origin[1]
            rotated[:, 0] = origin[0] + dx * cos_a - dy * sin_a
            rotated[:, 1] = origin[1] + dx * sin_a + dy * cos_a

            # 3 scale variations
            for scale in [0.88, 1.0, 1.12]:
                scaled = rotated.copy()
                scaled[:, 0] = origin[0] + (rotated[:, 0] - origin[0]) * scale
                scaled[:, 1] = origin[1] + (rotated[:, 1] - origin[1]) * scale

                # Jitter noise
                jitter = np.random.normal(0, 0.006, scaled.shape)
                noisy = scaled + jitter

                # Right hand
                r_pts = [
                    {"x": round(float(p[0]), 4), "y": round(float(p[1]), 4), "z": round(float(p[2]), 4)}
                    for p in noisy
                ]
                samples.append({
                    "label": label,
                    "landmarks": r_pts,
                    "hands": [r_pts]
                })

                # Left hand (mirrored)
                mirrored = noisy.copy()
                mirrored[:, 0] = 1.0 - mirrored[:, 0]
                l_pts = [
                    {"x": round(float(p[0]), 4), "y": round(float(p[1]), 4), "z": round(float(p[2]), 4)}
                    for p in mirrored
                ]
                samples.append({
                    "label": label,
                    "landmarks": l_pts,
                    "hands": [l_pts]
                })

    return samples

def main():
    print("Generating training samples for ALL 24 SIGNS from the chart...")
    samples = generate_augmented_dataset()
    print(f"Generated {len(samples)} high-precision samples across 24 sign classes!")

    dataset_service = DatasetService()
    # Replace existing dataset with the full 24-sign dataset
    dataset_service.save_samples([])
    added = dataset_service.add_samples(samples)
    print(f"Saved {added} samples into persistent dataset!")

    print("Training Random Forest Classifier on all 24 signs...")
    model_service = ModelService(dataset_service)
    result = model_service.train_model()
    print(f"Training Complete! Accuracy: {result['accuracy'] * 100:.1f}%")
    print(f"Active classes ({len(result['classes'])}): {result['classes']}")

if __name__ == "__main__":
    main()
